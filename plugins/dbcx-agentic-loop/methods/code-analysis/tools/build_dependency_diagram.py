#!/usr/bin/env python3
"""Generate the unit dependency diagram (draw.io) from the same JSON the D1 workbook is built from.

Usage: dbcx build_dependency_diagram.py [--png] [--include-standard]
Reads  analysis/inventory/inventory.json (edges, metrics) + analysis/inventory/inventory_analysis.json (verified categories)
Writes <project>/deliverables/<deliverables.D1.diagram> (+ .png when --png and the draw.io desktop CLI is installed).
Nothing is typed in by hand: labels (name, category, LOC) and edges come from the data, so a corrected analysis changes the diagram.
"""
import os, sys, subprocess, html, shutil, json
if "common" not in sys.modules: sys.path.insert(0, os.environ.get("DBCX_TOOLS") or sys.exit("DBCX_TOOLS is not set: run method tools as `dbcx <tool>`"))   # the engine by name, never by path
from common import RUN as ROOT, TOOLS, STATUS_PATH, project, labels, load_json, relp

PALETTE = ["#FFE6E6:#FF4B4B", "#FFF0E6:#FF744F", "#F3EEFA:#5B26B7", "#E9EDF7:#193773", "#E8EAF8:#3C4BC8", "#F5F5F5:#7A7A7A", "#EDEDED:#100C2A", "#F7F3EA:#C0AA81", "#F4F0F6:#A78DB6", "#FFFFFF:#CDCDCD"]

def find_cli():
    for c in ["drawio", "draw.io", "/Applications/draw.io.app/Contents/MacOS/draw.io", "/usr/bin/drawio", "/opt/drawio/drawio"]:
        p = shutil.which(c) or (c if os.path.exists(c) else None)
        if p: return p
    return None

def main():
    argv = sys.argv[1:]; inc_std = "--include-standard" in argv; p = project(); L = labels()
    inv = load_json("analysis/inventory/inventory.json"); ana = load_json("analysis/inventory/inventory_analysis.json", {"units": []})
    cat_of = {u["name"]: u["category"] for u in ana.get("units", [])}
    cats = p["unit"]["categories"]; colors = {c: PALETTE[i % len(PALETTE)].split(":") for i, c in enumerate(cats)}
    nodes = {n: {"category": cat_of.get(n, u["primary_category"]), "loc": sum(v for k, v in u["metrics"].items() if k in ("code", "templates", "ts", "js"))} for n, u in inv["units"].items()}
    edges, std_nodes = [], {}
    for e in inv["dependency_edges"]:
        if e["to_kind"] == "custom" and e["to"] in nodes: edges.append((e["from"], e["to"], "custom"))
        elif inc_std: std_nodes[e["to"]] = std_nodes.get(e["to"], 0) + 1; edges.append((e["from"], e["to"], "standard"))
    cells = ['<mxGraphModel adaptiveColors="auto"><root><mxCell id="0"/><mxCell id="1" parent="0"/>']; ids = {}
    for i, (n, d) in enumerate(sorted(nodes.items(), key=lambda kv: (kv[1]["category"], kv[0]))):
        fill, stroke = colors.get(d["category"], colors[cats[-1]]); ids[n] = f"n{i}"
        label = html.escape(f"<b>{n}</b><br><font style='font-size:9px'>{L.get(d['category'], d['category'])} · {d['loc']:,} LOC</font>")
        cells.append(f'<mxCell id="n{i}" value="{label}" style="rounded=1;whiteSpace=wrap;html=1;fillColor={fill};strokeColor={stroke};strokeWidth=2;fontFamily=Segoe UI;fontSize=11;" vertex="1" parent="1"><mxGeometry x="{(i%6)*220}" y="{(i//6)*110}" width="190" height="60" as="geometry"/></mxCell>')
    for k, n in enumerate(sorted(std_nodes)):
        ids[n] = f"s{k}"; cells.append(f'<mxCell id="s{k}" value="{html.escape(n)}" style="rounded=0;whiteSpace=wrap;html=1;fillColor=#FFFFFF;strokeColor=#9E9E9E;dashed=1;fontFamily=Segoe UI;fontSize=10;fontColor=#555555;" vertex="1" parent="1"><mxGeometry x="{(k%8)*170}" y="{600+(k//8)*70}" width="150" height="40" as="geometry"/></mxCell>')
    for e, (f, t, kind) in enumerate(edges):
        if f not in ids or t not in ids: continue
        style = "edgeStyle=orthogonalEdgeStyle;rounded=1;html=1;endArrow=block;endFill=1;strokeColor=" + ("#3C4BC8;strokeWidth=1.5;" if kind == "custom" else "#BBBBBB;dashed=1;")
        cells.append(f'<mxCell id="e{e}" style="{style}" edge="1" parent="1" source="{ids[f]}" target="{ids[t]}"><mxGeometry relative="1" as="geometry"/></mxCell>')
    sw = "".join(f"<span style='display:inline-block;padding:2px 8px;margin:2px;border:2px solid {s};background:{f};border-radius:4px;font-size:9px'>{L.get(c, c)}</span>" for c, (f, s) in colors.items())
    legend = L.get("_diagram_legend", "Dependency diagram of the custom units - solid arrow = declared dependency between custom units, dashed = standard unit. Generated by tools/build_dependency_diagram.py from analysis/inventory/*.json - do not edit by hand.") + "<br>" + sw
    cells.append(f'<mxCell id="legend" value="{html.escape(legend)}" style="text;html=1;whiteSpace=wrap;align=left;verticalAlign=top;fontFamily=Segoe UI;fontSize=10;strokeColor=#CDCDCD;fillColor=#FFFFFF;spacing=6;" vertex="1" parent="1"><mxGeometry x="0" y="-120" width="1100" height="70" as="geometry"/></mxCell>')
    cells.append("</root></mxGraphModel>")
    out = os.path.join(ROOT, "deliverables", p["deliverables"]["D1"]["diagram"]); os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write("".join(cells))
    print(f"{len(nodes)} custom nodes, {len(std_nodes)} standard nodes, {len(edges)} edges -> {relp(out, ROOT)}")
    cli = None if ("--no-layout" in argv or os.environ.get("DBCX_NO_DRAWIO_CLI")) else find_cli()
    if cli:
        def cli_run(args, what):   # the draw.io desktop CLI is a GUI app: never let a hang or a failure fail the build
            try:
                r = subprocess.run(args, capture_output=True, text=True, timeout=60); print(f"{what}:", "ok" if r.returncode == 0 else r.stderr[:300]); return r.returncode == 0
            except Exception as e: print(f"{what}: skipped ({type(e).__name__}) - .drawio written without it"); return False
        cli_run([cli, "-x", "-f", "xml", "--layout", "verticalFlow", "-o", out, out], "layout")
        if "--png" in argv and cli_run([cli, "-x", "-f", "png", "-e", "-b", "10", "-s", "2", "-o", out + ".png", out], "png"): print("png:", relp(out + ".png", ROOT))
    else: print("draw.io CLI not used: .drawio written without auto-layout (open in draw.io, Arrange > Layout; --no-layout / DBCX_NO_DRAWIO_CLI skip the CLI)")

if __name__ == "__main__":
    main()
