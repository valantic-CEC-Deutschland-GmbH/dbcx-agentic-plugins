#!/usr/bin/env python3
"""Rename-normalised template diff for SAP Commerce extensions (deterministic, read-only, no network).

Usage: dbcx template_diff <repo-root> <extension> [--template <vendor template>] [--files] [--json]
       (outside a run: python3 <plugin>/knowledge/platforms/sap-commerce/tools/template_diff.py ...)

A custom extension generated by extgen/modulegen (or an AddOn from yaddon) is a renamed copy of a vendor template shipped in the
repository (hybris/bin/modules/**/y*: yacceleratorstorefront, yacceleratorcore, yacceleratorfulfilmentprocess, ybackoffice, yaddon, yocc ...).
Without --template the template with the most files at the same renamed PATH is taken; paths that >= 20 % of all templates
match (the extgen skeleton: constants, manager, service, spring, items ...) and locale, message-bundle and dot files do not count; the
winner needs >= 8 remaining paths, >= 5 % of its own files covered, and >= 20 % of the extension's OR of the template's files;
otherwise yempty (the bare extgen skeleton) when >= 3 paths match, else no template. Committed test reports (reports/, web/reports/) are skipped. The rename is derived from the repository itself: extension name, classprefix
and Java package root (from `package` lines of file pairs with the same renamed name); each pair is also applied as its shortest
distinguishing token (e.g. yaccelerator -> <prefix>, so sibling-module references like yacceleratorfacades normalise too).
Every file of the extension (build output skipped) is then classified:
  unchanged-copy  identical to the template file after the rename
  cosmetic-copy   differs only in comments, blank lines or whitespace
  modified        a template counterpart exists and the code differs (changed_lines = lines of the extension not in the template)
  new             no template counterpart
Template files absent from the extension are counted as `template_only`. Line counts are non-blank lines incl. comments.
"""
import difflib, json, os, re, sys
from collections import Counter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sap_repo as R

TEXT_EXT = {".java", ".groovy", ".kt", ".jsp", ".jspf", ".tag", ".tagx", ".inc", ".xml", ".properties", ".impex", ".js", ".ts", ".css", ".less", ".scss", ".html", ".json", ".vm", ".txt", ".xsd", ".tld", ".csv"}
UBIQUITOUS = {"extensioninfo.xml", "project.properties", "buildcallbacks.xml", "external-dependencies.xml", "extensioninfo.xsd", ".classpath", ".project",
              "platformhome.properties", "build.xml", "ruleset.xml", "unmanaged-dependencies.txt", "readme.txt", "readme.md", "items.xsd", "beans.xsd"}
SKIP = R.SKIP | {"bin", "web/webroot/WEB-INF/classes"}
# Detection thresholds, tuned on a 31-extension estate: genuine templates matched 8 (yaddon on a small AddOn) to 842 non-skeleton paths;
# the strongest false match (a newer extgen skeleton) matched 5. An AddOn covers its small template well but not vice versa, hence the
# share is the larger of "share of the extension's files" and "share of the template's files".
MIN_PATHS, MIN_SHARE, MIN_TPL_SHARE = 8, 0.20, 0.05
SKELETON = re.compile(r"(^|/)\.[^/]+$|(^|/)resources/localization/|/messages/base(_\w+)?\.properties$|\.build\.number$|(^|/)AddTagLibsHere\.txt$")   # extgen output every template shares

REPORT_DIRS = ("reports", "web/reports")   # committed test/coverage reports: build output, not template or client code

def files_of(d):
    out = {}
    for dp, dns, fns in os.walk(d):
        rd = os.path.relpath(dp, d).replace(os.sep, "/")
        dns[:] = [x for x in dns if x not in SKIP and not x.startswith(".") and (x if rd == "." else f"{rd}/{x}") not in REPORT_DIRS]
        for f in fns: out[os.path.relpath(os.path.join(dp, f), d).replace(os.sep, "/")] = os.path.join(dp, f)
    return out

def read(p):
    try: return R.read_text(p)
    except OSError: return ""

def _bytes(p):
    with open(p, "rb") as f: return f.read()

def nonblank(t): return sum(1 for l in t.splitlines() if l.strip())

def package_of(p):
    m = re.search(r"^\s*package\s+([\w.]+)\s*;", read(p)[:4000], re.M); return m.group(1) if m else None

def _token(a, b):
    """Strip the longest common suffix: ('yacceleratorstorefront', 'acmestorefront') -> ('yaccelerator', 'acme'); None when too short to be safe."""
    i = 0
    while i < min(len(a), len(b)) and a[-1 - i] == b[-1 - i]: i += 1
    ta, tb = a[:len(a) - i], b[:len(b) - i]
    return (ta, tb) if i >= 4 and len(ta) >= 4 and not ta.endswith(".y") and ta != tb else None

def renames(unit, tpl, pkg_pair=None):
    pairs = []
    if pkg_pair:
        pairs += [pkg_pair, (pkg_pair[0].replace(".", "/"), pkg_pair[1].replace(".", "/"))]
        t = _token(*pkg_pair)
        if t: pairs += [t, (t[0].replace(".", "/"), t[1].replace(".", "/"))]
    for a, b in ((tpl["classprefix"], unit["classprefix"]), (tpl["name"], unit["name"])):
        if a and b and a != b:
            pairs.append((a, b)); t = _token(a, b)
            if t: pairs.append(t)
            if a.lower() != a: pairs.append((a.lower(), b.lower()))
    seen, out = set(), []
    for p in sorted(pairs, key=lambda p: -len(p[0])):
        if p[0] and p[0] not in seen: seen.add(p[0]); out.append(p)
    return out

def apply(s, pairs):
    for a, b in pairs: s = s.replace(a, b)
    return s

def strip_comments(t, ext):
    if ext in (".java", ".groovy", ".kt", ".js", ".ts", ".css", ".less", ".scss"): t = re.sub(r"/\*.*?\*/", "", t, flags=re.S); t = re.sub(r"(?m)^\s*//.*$", "", t)
    if ext in (".xml", ".jsp", ".jspf", ".tag", ".tagx", ".inc", ".html", ".xsd", ".tld", ".vm"): t = re.sub(r"<!--.*?-->", "", t, flags=re.S); t = re.sub(r"<%--.*?--%>", "", t, flags=re.S)
    if ext in (".properties", ".impex", ".csv"): t = re.sub(r"(?m)^\s*[#!].*$", "", t)
    return [re.sub(r"\s+", " ", l).strip() for l in t.splitlines() if l.strip()]

def pkg_pair(unit_files, tpl_files, pairs):
    """Most frequent (template package root, extension package root) over Java files with the same renamed name."""
    by_base = {}
    for r, p in tpl_files.items():
        if r.endswith(".java"): by_base.setdefault(apply(os.path.basename(r), pairs), []).append(p)
    c = Counter()
    for r, p in unit_files.items():
        for tp in by_base.get(os.path.basename(r), [])[:1] if r.endswith(".java") else []:
            a, b = package_of(tp), package_of(p)
            if a and b:
                sa, sb = a.split("."), b.split("."); k = 0
                while k < min(len(sa), len(sb)) - 1 and sa[-1 - k] == sb[-1 - k]: k += 1
                c[(".".join(sa[:len(sa) - k]), ".".join(sb[:len(sb) - k]))] += 1
    return c.most_common(1)[0][0] if c else None

def matched(unit, tpl, unit_files, tpl_files):
    """Paths of the extension that exist in the template after the rename (ubiquitous descriptors and skeleton files ignored), and the
    number of template files considered."""
    pairs = renames(unit, tpl, pkg_pair(unit_files, tpl_files, renames(unit, tpl)))
    tp = {apply(r, pairs) for r in tpl_files if os.path.basename(r).lower() not in UBIQUITOUS and not SKELETON.search(r)}
    return {r for r in unit_files if r in tp}, len(tp)

def templates_of(tree):
    return {n: e for n, e in tree.items() if e["standard"] and n.startswith("y") and n != "yempty"} | ({"yempty": tree["yempty"]} if "yempty" in tree else {})

def detect(unit, tree, unit_files=None, cache=None):
    """(template, share, matched paths) or None. Every extgen-generated extension shares the extgen skeleton (constants, manager, service,
    setup, spring, items, beans, web.xml ...) with most templates, so paths that >= 20 % of the templates match are skeleton and do not count;
    the template with the most remaining matches wins if it has >= MIN_PATHS of them, covers >= MIN_TPL_SHARE of its own files and
    max(share of the extension's files, share of the template's files) >= MIN_SHARE; otherwise yempty (the bare skeleton) when it
    matches >= 3 paths."""
    unit_files = unit_files or files_of(unit["dir"]); ms = {}
    for n, t in templates_of(tree).items():
        tf = cache.setdefault(n, files_of(t["dir"])) if cache is not None else files_of(t["dir"])
        ms[n] = matched(unit, t, unit_files, tf)
    freq = Counter(p for m, _ in ms.values() for p in m); skel = {p for p, c in freq.items() if c >= max(2, 0.2 * len(ms))}
    nu = sum(1 for r in unit_files if os.path.basename(r).lower() not in UBIQUITOUS and not SKELETON.search(r) and r not in skel) or 1
    ok = []
    for n, (m, nt) in ms.items():
        k = len(m - skel); st = k / max(1, nt - len(m & skel))
        if n != "yempty" and k >= MIN_PATHS and st >= MIN_TPL_SHARE and max(k / nu, st) >= MIN_SHARE: ok.append((k, n, round(max(k / nu, st), 3)))
    if ok: k, n, s = max(ok); return n, s, k
    m = len(ms.get("yempty", (set(), 0))[0])
    return ("yempty", "skeleton only", m) if m >= 3 else None

def diff(unit, tpl, unit_files=None, tpl_files=None, with_files=False):
    uf = unit_files or files_of(unit["dir"]); tf = tpl_files or files_of(tpl["dir"])
    base = renames(unit, tpl); pp = pkg_pair(uf, tf, base); pairs = renames(unit, tpl, pp)
    tmap = {apply(r, pairs): p for r, p in tf.items()}
    cls = {"unchanged-copy": [], "cosmetic-copy": [], "modified": [], "new": []}; loc = Counter(); changed = 0; per = {}
    for r, p in sorted(uf.items()):
        ext = os.path.splitext(r)[1].lower(); t = read(p) if ext in TEXT_EXT else None; n = nonblank(t) if t is not None else 0
        tp = tmap.get(r)
        if not tp: k = "new"
        elif t is None: k = "unchanged-copy" if _bytes(p) == _bytes(tp) else "modified"
        else:
            tt = apply(read(tp), pairs)
            if tt == t: k = "unchanged-copy"
            else:
                a, b = strip_comments(tt, ext), strip_comments(t, ext)
                if a == b: k = "cosmetic-copy"
                else:
                    k = "modified"; d = sum(1 for l in difflib.ndiff(a, b) if l.startswith("+ ")); changed += d; per[r] = d
        cls[k].append(r); loc[k] += n
    res = {"extension": unit["name"], "template": tpl["name"], "template_dir": tpl["dir"], "renames": pairs,
           "counts": {k: len(v) for k, v in cls.items()} | {"template_only": len(set(tmap) - set(uf))}, "loc": dict(loc), "modified_changed_lines": changed,
           "rule": "RULE: rename-normalised diff (renames " + "; ".join(f"{a} -> {b}" for a, b in pairs) + f") of {unit['name']} against the vendor template {tpl['name']}; "
                   "unchanged-copy = identical after the rename, cosmetic-copy = only comments/blank lines/whitespace differ, modified = code differs "
                   "(changed_lines = extension lines not in the template), new = no template counterpart; lines = non-blank incl. comments; build output and reports/, web/reports/ skipped."}
    if with_files: res["files"] = {k: v for k, v in cls.items()}; res["modified_lines_per_file"] = per
    return res

def run(root, name, template=None, with_files=False):
    L = R.layout(root); tree = R.extensions_in_tree(L["bin"])
    if name not in tree: sys.exit(f"extension {name} not found below {L['bin']}")
    u = tree[name]
    if template:
        if template not in tree: sys.exit(f"template {template} not found below {L['bin']}")
        t = template; s = m = None
    else:
        best = detect(u, tree)
        if not best: return {"extension": name, "template": None, "rule": "RULE: no vendor template (not even the yempty skeleton) matches enough renamed file paths - not a template copy by this test."}
        t, s, m = best
    r = diff(u, tree[t], with_files=with_files); r["detection"] = ({"share": s, "matched_non_skeleton_paths": m} if s != "skeleton only" else {"skeleton_only": True, "matched_paths": m}) if s is not None else "explicit --template"
    for k in ("template_dir",): r[k] = os.path.relpath(r[k], L["root"])
    return r

def main():
    a = sys.argv[1:]
    if len(a) < 2 or a[0].startswith("-"): sys.exit(__doc__)
    r = run(a[0], a[1], a[a.index("--template") + 1] if "--template" in a else None, "--files" in a or "--json" in a)
    if "--json" in a: print(json.dumps(r, indent=1, ensure_ascii=False)); return
    if not r.get("template"): print(r["rule"]); return
    print(f"{r['extension']} vs template {r['template']} ({r['template_dir']}; detection {r['detection']})")
    for k in ("unchanged-copy", "cosmetic-copy", "modified", "new"): print(f"  {k:15s} files {r['counts'][k]:5d}  lines {r['loc'].get(k, 0):7d}")
    print(f"  template_only   files {r['counts']['template_only']:5d}  | changed lines in modified files: {r['modified_changed_lines']}")
    if "--files" in a:
        for f, d in sorted(r["modified_lines_per_file"].items(), key=lambda x: -x[1])[:40]: print(f"    modified {f} (+{d})")
    print(r["rule"])

if __name__ == "__main__":
    main()
