#!/usr/bin/env python3
"""the method generator - an own method's card (`<method dir>/method-card.json`)
-> a method pack in the same folder that runs on the generic providers without any Python of its own.

Usage: dbcx method generate <name> [--closest <plugin method>] [--force] [--dry-run] [--json]
       (also dbcx method_generate <name> ...)
The method folder: $DBCX_METHOD_DIR when set, else <engagement>/methods/<name>/ (a run that is its own engagement: <run>/methods/<name>/);
never a folder of the plugin's methods/. Refused unless the card says `confirmed: true`.

Writes (every file with a marker: JSON a top-level `_generated` {by, card_sha256, sha256}, Markdown a first line
`<!-- generated by dbcx method generate; sha256 <hash> -->`; the hash covers the body without the marker):
  method.json               fixed skeleton: preflight -> [inventory + gauntlet] -> scope waves + gauntlet -> consolidation(s) + gauntlet -> build
                            -> gate; scopes.discover generic:<source> (or the card's own tool), defaults.units = unit.source_config,
                            "datasets": "generic", evidence bases on the plugin baseline (method_guard.guard_report stays silent unless the
                            card asks for public unit names), critics.standard from the card, gate personas and key questions, init_fields,
                            artefacts, lint, version 0.1.0, engine = VERSION MAJOR.MINOR, origin {type, closest}
  kinds.json                the per-unit kind (one section per topic: text | list | table | rating = a scored table with the anchors), the
                            inventory kind (unit.source inventory), one kind per consolidation view
  deliverables.<lang>.json  per card language: Management_Summary, README, Parameters, the card's sheets (table sheets over the generic
                            datasets `<kind>` / `<kind>.<table>`), detail sheets the card's formulas need, an Overview sheet for the
                            aggregates per unit or per value, Claims
  labels.<lang>.json, briefs/<role>.md (analyst, inventory, consolidate[-<X>], critic-client, critic-standard, gate, research),
  plan.md, notes.md
Structure is borrowed from the closest plugin method (--closest, else the card's origin.closest) only where an answer matches it: model
profiles and claim caps, its lean profile when the card asks for lean, its inventory inputs for an inventory unit source, its gate
personas when the card names none.

Re-generation: a generated file that is unchanged since it was written is rewritten (or deleted when the card no longer produces it);
a generated file edited by hand, or any file at a generated path that the generator did not write, is kept and reported - `--force`
overwrites it. Files the generator never produces (datasets.py, briefing.py, critics.py, tools/, fixtures/, smoke.sh ...) are never
touched; a hand-written datasets.py replaces the generic datasets, so the generator lists the dataset names it must provide.

Formula hints (card columns of kind `formula`: `formula`; aggregates: `formula_hint`). Names are sheet and column names of the same
workbook (any card language, case and `_` / `-` / space insensitive), topic ids or titles, field names:
  =<Excel formula>         [Column] = this row's cell, [Sheet.Column] = that column's range, {Parameter} = a parameter of the workbook,
                           {L:token} = the display label of an enum token
  count <Sheet>            sum | average | min | max <Sheet>.<Column>          share <Sheet> where <condition>
  ... where <Column> <op> <value> [and ...]   (op = <> < > <= >=; a value is a number, an enum token or a quoted text)
  On a per-unit sheet a hint over another sheet counts that unit's rows only. An aggregate (`aggregates`) becomes a KPI on the
  Management_Summary; `... per <unit noun>` becomes an Overview block with one row per unit, `... by <Column>` one row per value.
A hint that does not follow this is refused with the reason, nothing is written.
"""
