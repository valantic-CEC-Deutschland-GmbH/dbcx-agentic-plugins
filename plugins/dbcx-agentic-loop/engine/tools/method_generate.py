    def critics(self):
        M = self.M; out = []
        for c in lst(self.ev.get("standard_critics")):
            if postponed(c): continue
            s = c.get("scores", "all")
            if isinstance(s, str) and s.strip().startswith("{"): s = json.loads(s)
            src = c.get("sources") or {}
            x = {"id": slug(c.get("id") or "standard", "-"), "persona": txt(c.get("persona"), "en"), "sources": {"packs": list(src.get("packs") or []), "domains": list(src.get("domains") or []), "reference": src.get("reference", True) is not False}}
            if s == "all" or not s: x["scores"] = "all"
            else:
                tps = []
                for t in (s.get("topics") if isinstance(s, dict) else s) or []:
                    tp = M.topic(t)
                    if not tp: refuse(f"standard critic {x['id']}: topic '{t}' is no topic of the card")
                    tps.append(tp["key"])
                    tps += [f"{sh['wb']}/{sheet_name(sh['names'][M.L0])}" for sh in M.sheets if sh["src"] == ("topic", tp["id"])]
                x["scores"] = {"topics": list(dict.fromkeys(tps))}
            out.append(x)
        if not any(c["scores"] == "all" for c in out) and out:   # every claim needs a standard critic: the parts outside the topics go to the first critic
            have = {k for c in out for k in c["scores"]["topics"]}
            extra = ([M.inv["kind"]] if M.inv else []) + [c["kind"] for c in M.cons.values()] + ["summary"] + [t["key"] for t in M.topics.values() if t["key"] not in have and t["key"] != "summary"] \
                + [f"{sh['wb']}/{sheet_name(sh['names'][M.L0])}" for sh in M.sheets if sh["src"] == ("unit",)]
            out[0]["scores"]["topics"] = list(dict.fromkeys(out[0]["scores"]["topics"] + extra))
            M.notes.append(f"no standard critic scores all topics: standard-{out[0]['id']} also scores the inventory, the cross-unit views and the per-unit sheets ({', '.join(extra)}), so every claim has a standard critic")
        tc = {k for c in out if c["scores"] != "all" for k in c["scores"]["topics"]}
        if not any(c["scores"] == "all" for c in out):
            lost = [t["id"] for t in M.topics.values() if t["key"] != "summary" and t["key"] not in tc]
            if lost: refuse(f"topic(s) {', '.join(lost)} have no standard critic - give one critic `scores: all` or add them to a critic's topics")
        return out

