    def wb_sheets(self, wb): return [s for s in self.sheets if s["wb"] == wb]

    def find_sheet(self, ref, wb):
        r = norm(ref)
        for s in self.wb_sheets(wb):
            if r in {norm(x) for x in s["names"].values()} | {norm(s["key"])}: return s
        t = self.topic(ref)
        if t and t["form"] in ("table", "rating"):
            s = next((s for s in self.wb_sheets(wb) if s["src"] == ("topic", t["id"])), None)
            return s or self.topic_sheet(wb, t)   # a formula over a topic this workbook does not show yet: its detail sheet joins the workbook
        c = self.cons_of(ref)
        if c: return next((s for s in self.wb_sheets(wb) if s["src"] == ("cons", c["id"])), None)
        if self.inv and r in ("inventory", norm(self.inv["kind"])): return next((s for s in self.wb_sheets(wb) if s["src"] == ("inv",)), None)
        if r in {norm(x) for x in texts(self.plural) + texts(self.noun)} | {"unit", "units"}: return next((s for s in self.wb_sheets(wb) if s["src"] == ("unit",)), None)
