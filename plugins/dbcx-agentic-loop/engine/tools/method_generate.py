    def find_col(self, sh, ref):
        r = norm(ref)
        for c in sh["cols"]:
            if r in {norm(x) for x in c["names"].values()} | {norm(c["id"])} | ({norm(c["field"])} if c.get("field") else set()): return c
        if r in {"unit", "name"} | {norm(x) for x in texts(self.noun)}: return sh["cols"][0] if sh["cols"] and sh["cols"][0].get("unit") else None
        return None

    def split_ref(self, ref, wb, here):
        """'Sheet.Column' | 'Sheet' | 'Column' (this sheet) -> (sheet, column or None)"""
        ref = ref.strip()
        for i in [m.start() for m in re.finditer(r"\.", ref)][::-1]:
            s = self.find_sheet(ref[:i], wb)
            if s:
                c = self.find_col(s, ref[i + 1:])
                if not c: raise HintError(f"sheet {s['names'][self.L0]} has no column '{ref[i + 1:]}'")
                return s, c
        s = self.find_sheet(ref, wb)
        if s: return s, None
        if here:
            c = self.find_col(here, ref)
            if c: return here, c
        raise HintError(f"'{ref}' names no sheet or column of workbook {wb}")

    def numeric(self, col):
        if col.get("f") and col["f"].get("_added") and col["f"]["t"] == "s": col["f"]["t"] = "i"

    def crit(self, col, op, val):
        val = val.strip(); op = {"!=": "<>", "==": "="}.get(op, op)
        if re.fullmatch(r"-?\d+(\.\d+)?", val): return val if op == "=" else f'"{op}{val}"'
        if val[:1] in "\"'" and val[-1:] == val[:1]: v = val[1:-1]
        else:
            f = col.get("f") or {}; low = val.lower()
            tok = next((str(x) for x in f.get("enum") or [] if str(x).lower() == low), None)
            if tok is None and f.get("t") == "b": tok = {"yes": "true", "ja": "true", "true": "true", "no": "false", "nein": "false", "false": "false"}.get(low)
            if tok is None and col.get("formula") and low in ("yes", "ja", "true", "no", "nein", "false"): tok = "yes" if low in ("yes", "ja", "true") else "no"   # a formula column that shows {L:yes} / {L:no}
            v = f"{{L:{tok}}}" if tok is not None else val
        return f'"{"" if op == "=" else op}{v}"'

    def compile(self, hint, wb, here=None, aggregate=False):
        """-> (formula with {rng:@key@.id} markers, number format, group) ; group = ("units", sheet) | ("by", sheet, column) for an aggregate block"""
        h = str(hint or "").strip()
        if not h: raise HintError("empty formula hint")
        if h.startswith("="): return self.compile_excel(h, wb, here), None, None
        m = re.match(r"(?i)^(count|number|sum|total|average|avg|mean|min|minimum|max|maximum|share|first)\s+(?:of\s+)?(.+)$", h)
        if not m: raise HintError(f"'{h}' is no formula: start with '=' (Excel) or with count | sum | average | min | max | share | first")
        agg = {"number": "count", "total": "sum", "avg": "average", "mean": "average", "minimum": "min", "maximum": "max"}.get(m.group(1).lower(), m.group(1).lower())
        rest = m.group(2).strip(); group = None
        g = re.search(r"(?i)\s+(per|by|je|nach)\s+(.+)$", rest)
        if g: rest = rest[:g.start()].strip(); group = (g.group(1).lower(), g.group(2).strip())
        if group and not aggregate: raise HintError(f"'{h}': 'per' / 'by' belongs to an aggregate (the workbook's totals), not to a column")
        parts = re.split(r"(?i)\s+(?:where|wo|wenn)\s+", rest, maxsplit=1); ref = parts[0]; cond = parts[1] if len(parts) > 1 else ""
        sh, col = self.split_ref(ref, wb, None if aggregate else here)
        if agg in ("sum", "average", "min", "max", "first") and not col: raise HintError(f"'{h}': {agg} needs a column (<Sheet>.<Column>)")
        if col and agg in ("sum", "average", "min", "max"): self.numeric(col)
        R = lambda c: f"{{rng:@{sh['key']}@.{c['id']}}}"
        pairs = []
        if here and not aggregate and here["src"] == ("unit",) and sh is not here and sh["cols"] and sh["cols"][0].get("unit"): pairs.append((R(sh["cols"][0]), "{cell:unit}"))
        grp = None
        if group:
            if norm(group[1]) in {norm(x) for x in texts(self.noun) + texts(self.plural)} | {"unit", "units"}:
                if not (sh["cols"] and sh["cols"][0].get("unit")): raise HintError(f"'{h}': sheet {sh['names'][self.L0]} has no {txt(self.noun, self.L0)} column")
                pairs.append((R(sh["cols"][0]), "{row}")); grp = ("units", sh)
            else:
                gc = self.find_col(sh, group[1])
                if not gc: raise HintError(f"'{h}': sheet {sh['names'][self.L0]} has no column '{group[1]}'")
                pairs.append((R(gc), "{row}")); grp = ("by", sh, gc)
        conds = []
        for part in [x for x in re.split(r"(?i)\s+(?:and|und)\s+", cond) if x.strip()] if cond else []:
            cm = re.match(r"^(.+?)\s*(<=|>=|<>|!=|==|=|<|>)\s*(.+)$", part.strip())
            if not cm: raise HintError(f"'{h}': condition '{part}' is not <Column> <op> <value>")
            cc = self.find_col(sh, cm.group(1))
            if not cc: raise HintError(f"'{h}': sheet {sh['names'][self.L0]} has no column '{cm.group(1)}'")
            conds.append((R(cc), self.crit(cc, cm.group(2), cm.group(3))))
        anycol = sh["cols"][0]
        def ifs(fn, target, ps): return f"{fn}({target + ',' if target else ''}{','.join(f'{a},{b}' for a, b in ps)})"
        nf = None
        if agg == "first":   # the value of the unit's first row (a topic with one row per unit: its value)
            if aggregate or len(pairs) != 1 or conds: raise HintError(f"'{h}': first takes a column of a detail sheet, on a per-unit sheet only, without where")
            f = f'IFERROR(INDEX({R(col)},MATCH({pairs[0][1]},{pairs[0][0]},0)),"")'
        elif agg == "count": f = ifs("COUNTIFS", "", pairs + conds) if pairs + conds else f"COUNTA({R(col or anycol)})"
        elif agg == "share":
            if not conds: raise HintError(f"'{h}': share needs a condition (share <Sheet> where <Column> = <value>)")
            den = ifs("COUNTIFS", "", pairs) if pairs else f"COUNTA({R(col or anycol)})"
            f = f'IFERROR({ifs("COUNTIFS", "", pairs + conds)}/{den},"")'; nf = "0%"
        else:
            fn = {"sum": "SUMIFS", "average": "AVERAGEIFS", "min": "MINIFS", "max": "MAXIFS"}[agg]
            f = ifs(fn, R(col), pairs + conds) if pairs + conds else f"{agg.upper()}({R(col)})"
            if agg == "average": f = f'IFERROR({f},"")'; nf = "0.0" if not col.get("f") or col["f"].get("t") != "f" else "0.00"
        return "=" + f, nf, grp

    def compile_excel(self, h, wb, here):
        def br(m):
            own = self.find_col(here, m.group(1)) if here and "." not in m.group(1) else None   # a bare name: this sheet's column first
            if own: return f"{{cell:{own['id']}}}"
            sh, col = self.split_ref(m.group(1), wb, here)
            if not col: raise HintError(f"'[{m.group(1)}]' names a sheet - write [Sheet.Column]")
            if sh is here: return f"{{cell:{col['id']}}}"
            return f"{{rng:@{sh['key']}@.{col['id']}}}"
        def nb(m):   # arithmetic next to a column: a field the card added has numbers
            for x in re.finditer(r"\[([^\]]+)\]", m.group(0)):
                try: sh, col = self.split_ref(x.group(1), wb, here); col and self.numeric(col)
                except HintError: pass
            return m.group(0)
        re.sub(r"\[[^\]]+\]\s*[*/+\-]|[*/+\-]\s*\[[^\]]+\]", nb, h)
        def pr(m):
            body = m.group(1)
            if body.startswith(("L:", "rng:", "cell:", "col:", "p:", "pt:", "row", "r}", "MAXR")) or body in ("row", "r", "MAXR"): return m.group(0)
            pk = next((k for k, v in self.params.get(wb, {}).items() if norm(body) in {norm(x) for x in v["names"]}), None)
            if pk is None: raise HintError(f"'{{{body}}}' names no parameter of workbook {wb}")
            return f"{{p:@P{pk}@}}"
        s = re.sub(r"\{([^{}]+)\}", pr, h)
        return re.sub(r"\[([^\]]+)\]", br, s)

    def compile_all(self):
        errs = []
        for w in self.card["result"]["workbooks"]:
            self.params[w["id"]] = {str(i): {"names": texts(p["name"]), "p": p} for i, p in enumerate(lst(w.get("parameters"))) if not postponed(p)}
        for sh in list(self.sheets):
            for c in sh["cols"]:
                if c.get("formula") and "_compiled" not in c:
                    try: c["_compiled"], c["_nf"], _ = self.compile(c["formula"], sh["wb"], sh)
                    except HintError as e: errs.append(f"workbook {sh['wb']}, sheet {sh['names'][self.L0]}, column {c['names'][self.L0]}: {e}")
        for w in self.card["result"]["workbooks"]:
            out = []
            for a in lst(w.get("aggregates")):
                if postponed(a): continue
                try: f, nf, grp = self.compile(a.get("formula_hint") or a.get("formula"), w["id"], None, aggregate=True)
                except HintError as e: errs.append(f"workbook {w['id']}, aggregate {txt(a.get('what'), self.L0)}: {e}"); continue
                out.append({"what": a.get("what"), "f": f, "nf": nf, "grp": grp, "hint": a.get("formula_hint")})
            self.aggs[w["id"]] = out
        if errs: refuse("the formula hints of the card cannot be read - nothing was written:\n  " + "\n  ".join(errs) + "\nWrite a hint as '=<Excel formula>' with [Column], [Sheet.Column] and {Parameter}, or as 'count | sum | average | min | max | share <Sheet>[.<Column>] [where <Column> = <value>] [per <unit> | by <Column>]'.")

    def build(self):
        self.build_topics(); self.build_inventory(); self.build_consolidations()
        for w in self.card["result"]["workbooks"]:
            if w["id"] in [x["id"] for x in self.card["result"]["workbooks"][:self.card["result"]["workbooks"].index(w)]]: refuse(f"workbook id {w['id']} used twice")
        self.card_sheets(); self.auto_sheets(); self.complete_sheets(); self.compile_all()
        return self


