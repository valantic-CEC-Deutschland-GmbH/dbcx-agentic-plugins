class Refused(SystemExit):
    pass


def refuse(msg): raise Refused(msg)


def txt(v, lang):
    """a card text: a string, or {lang: text} for several languages (the first one as the fallback)"""
    if isinstance(v, dict): return str(v.get(lang) or next(iter(v.values()), ""))
    return "" if v is None else str(v)


def texts(v): return [str(x) for x in v.values()] if isinstance(v, dict) else [str(v)] if v not in (None, "") else []


def norm(s): return re.sub(r"[\s_\-]+", " ", str(s or "").strip().lower())


def slug(s, sep="_"):
    s = str(s or "").lower()
    for a, b in (("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("ß", "ss")): s = s.replace(a, b)
    return re.sub(r"[^a-z0-9]+", sep, s).strip(sep)[:40].strip(sep) or "x"


def sheet_name(s):
    """an Excel sheet name the engine can address unquoted (letters, digits, `_`; at most 31 characters)"""
    for a, b in (("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("Ä", "Ae"), ("Ö", "Oe"), ("Ü", "Ue"), ("ß", "ss")): s = str(s).replace(a, b)
    n = re.sub(r"[^A-Za-z0-9_]+", "_", s).strip("_")[:31].strip("_") or "Sheet"
    return f"S_{n}"[:31] if re.match(r"^([A-Za-z]{1,3}\d+|\d)", n) else n


def jhash(o): return hashlib.sha256(json.dumps(o, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def engine_version():
    v = (open(os.path.join(PLUGIN, "VERSION"), encoding="utf-8").read().strip() if os.path.exists(os.path.join(PLUGIN, "VERSION")) else "0.0")
    return ".".join(v.split(".")[:2])


# ------------------------------------------------------------------ the method folder and the card
def method_dir(name):
    env = os.environ.get("DBCX_METHOD_DIR")
    cands = [os.path.abspath(os.path.expanduser(env))] if env else []
    cands += [os.path.join(r, name) for r in method_roots() if os.path.realpath(r) != os.path.realpath(METHODS)]
    for d in cands:
        if os.path.realpath(d).startswith(os.path.realpath(METHODS) + os.sep): refuse(f"REFUSED: {d} is a method of the plugin - the generator writes own methods only")
        if os.path.exists(os.path.join(d, CARD)): return d
    refuse(f"no method card for '{name}': expected {CARD} in " + (", ".join(cands) or "<engagement>/methods/<name>/ (run it inside the engagement, or set DBCX_METHOD_DIR)"))


def postponed(v): return isinstance(v, dict) and set(v) == {"postponed"}


def lst(v):
    """the answered items of a list slot of the card ([] for a postponed or missing slot)"""
    return [x for x in v if not postponed(x)] if isinstance(v, list) else []


def load_card(d, name):
    card = read_json(os.path.join(d, CARD), None)
    if not isinstance(card, dict): refuse(f"{os.path.join(d, CARD)} is no JSON object")
    if card.get("name") and card["name"] != name: refuse(f"the card in {d} is for '{card['name']}', not '{name}'")
    if card.get("confirmed") is not True: refuse(f"REFUSED: the method card of '{name}' is not confirmed - show the card to the user and confirm it (dbcx method confirm {name}) before generating")
    miss = []
    for path in ("unit.noun", "unit.source", "topics", "evidence.standard_critics", "result.workbooks"):
        cur = card
        for p in path.split("."): cur = cur.get(p) if isinstance(cur, dict) else None
        if cur in (None, "", []) or postponed(cur): miss.append(path)
    if miss: refuse(f"the card of '{name}' cannot generate a method without: {', '.join(miss)} (answer them, or they block the framework: a unit, at least one topic, one standard critic and one workbook)")
    card["topics"] = lst(card["topics"]); card["result"]["workbooks"] = lst(card["result"]["workbooks"])
    if not card["topics"] or not card["result"]["workbooks"]: refuse(f"the card of '{name}' has no answered topic or workbook")
    src = card["unit"]["source"]
    if src not in ("list", "workbook", "folders", "inventory", "tool"): refuse(f"unit.source '{src}' is not list | workbook | folders | inventory | tool")
    return card


