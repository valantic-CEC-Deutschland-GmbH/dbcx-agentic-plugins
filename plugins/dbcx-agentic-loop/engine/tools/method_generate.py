IMPLICIT_DEFS = {"score": {"t": "i", "enum": list(range(11)), "req": True}, "rationale": {"t": "s", "req": True}, "evidence": {"t": "l", "req": True},
                 "confidence": {"t": "s", "enum": ["high", "medium", "low"], "req": True}}   # the generator's definitions of the implicit fields (enums, required)


def implicit_fields(topic):
    """{field: definition} a card topic brings without naming them (method.implicit_fields, Amendment 2: the names and their order; an
    `aspect` of a rating topic without fields of its own comes first, it keys the row)"""
    fs = card_implicit(topic); fs = [f for f in fs if f["name"] == "aspect"] + [f for f in fs if f["name"] != "aspect"]
    return {slug(f["name"]): dict(IMPLICIT_DEFS.get(f["name"], {"t": f.get("type") or "s"})) for f in fs}


