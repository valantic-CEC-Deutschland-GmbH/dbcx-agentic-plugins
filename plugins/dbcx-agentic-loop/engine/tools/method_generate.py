def texts_l(v, lang): return [txt(x, lang) for x in lst(v)] if isinstance(v, list) else ([txt(v, lang)] if v and not postponed(v) else [])


# ------------------------------------------------------------------ writing with the re-generation rules
def render(rel, body, card_hash):
    if isinstance(body, dict):
        return json.dumps(dict({"_generated": {"by": MARK_BY, "card_sha256": card_hash, "sha256": jhash(body)}}, **body), indent=1, ensure_ascii=False) + "\n"
    return f"<!-- generated by dbcx method generate; sha256 {hashlib.sha256(body.encode('utf-8')).hexdigest()} -->\n" + body


def state(path):
    """'absent' | 'generated' (unchanged since written) | 'edited' (generated, then changed by hand) | 'own' (not written by the generator)"""
    if not os.path.exists(path): return "absent"
    raw = open(path, encoding="utf-8").read()
    if path.endswith(".json"):
        try: d = json.loads(raw)
        except ValueError: return "own"
        g = d.pop("_generated", None) if isinstance(d, dict) else None
        if not isinstance(g, dict) or g.get("by") != MARK_BY: return "own"
        return "generated" if jhash(d) == g.get("sha256") else "edited"
    m = MD_MARK.match(raw)
    if not m: return "own"
    return "generated" if hashlib.sha256(raw[m.end():].encode("utf-8")).hexdigest() == m.group(1) else "edited"


def generate(name, closest=None, force=False, dry=False):
    d = method_dir(name); card = load_card(d, name)
    if (card.get("origin") or {}).get("type") == "derived" and not force: refuse(f"REFUSED: '{name}' is a derived method - its files are the copy of a plugin method; generating replaces them with a pack built from the card alone. Run with --force only if that is intended")
    runs = open_runs(name) if not dry else []   # a run of this method still open - rewriting the pack would change its method hash and stop it
    if runs: refuse(f"REFUSED: a run of '{name}' is still open ({', '.join(runs)}) - finish it (or start the next run after generating); a method changes between runs, never during one")
    cname = closest or (card.get("origin") or {}).get("closest")
    cl = None
    if cname:
        p = os.path.join(METHODS, cname, "method.json")
        if not os.path.exists(p): refuse(f"--closest '{cname}' is no plugin method (available: {', '.join(sorted(n for n in os.listdir(METHODS) if os.path.exists(os.path.join(METHODS, n, 'method.json'))))})")
        cl = dict(read_json(p), name=cname)
    if card["unit"]["source"] == "tool":
        tool = str((card["unit"].get("source_config") or {}).get("tool") or "discover")
        if not os.path.exists(os.path.join(d, "tools", f"{tool}.py")): refuse(f"unit.source tool: {os.path.join(d, 'tools', tool + '.py')} does not exist - the method's own discover tool comes first")
    prev = read_json(os.path.join(d, "method.json"), {}) if os.path.exists(os.path.join(d, "method.json")) else {}
    M = Model(card, cl).build(); pk = Pack(M, card, cl, prev); files = pk.files()
    ch = jhash(card); report = {"method": name, "dir": d, "written": [], "unchanged": [], "kept": [], "removed": [], "notes": M.notes}
    plan = []
    for rel, body in files.items():
        p = os.path.join(d, rel); st = state(p); new = render(rel, body, ch)
        if st == "generated" and open(p, encoding="utf-8").read() == new: report["unchanged"].append(rel); continue
        if st in ("edited", "own") and not force: report["kept"].append(f"{rel} ({'edited by hand since it was generated' if st == 'edited' else 'not written by the generator'})"); continue
        plan.append((p, new)); report["written"].append(rel)
    for root, dirs, fs in os.walk(d):   # generated files the card no longer produces
        dirs[:] = [x for x in dirs if x not in ("__pycache__", "tools", "fixtures")]
        for f in fs:
            p = os.path.join(root, f); rel = os.path.relpath(p, d).replace(os.sep, "/")
            if rel in files or f.endswith(NEVER) or not f.endswith((".json", ".md")) or rel == CARD: continue
            st = state(p)
            if st == "generated": plan.append((p, None)); report["removed"].append(rel)
            elif st == "edited": report["kept"].append(f"{rel} (generated earlier, edited by hand, no longer produced by the card)")
    if os.path.exists(os.path.join(d, "datasets.py")):
        names = sorted({sh["dataset"] for l in M.langs for w in files[f"deliverables.{l}.json"]["deliverables"].values() for sh in w["sheets"] if sh.get("type") == "table"})
        M.notes.append("datasets.py (hand-written) replaces the generic datasets: it must provide " + ", ".join(names) + " (import generic_datasets and extend its DATASETS)")
    if not dry:
        for p, new in plan:
            if new is None: os.remove(p); continue
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as fh: fh.write(new)
    report["dry_run"] = dry
    return report


def main():
    a = sys.argv[1:]
    if not a or a[0] in ("-h", "--help"): print(__doc__); sys.exit(0 if a else 2)
    if a[0] == "generate": a = a[1:]
    name = next((x for x in a if not x.startswith("--") and (a.index(x) == 0 or a[a.index(x) - 1] != "--closest")), None)
    if not name: print(__doc__); sys.exit(2)
    closest = a[a.index("--closest") + 1] if "--closest" in a and a.index("--closest") + 1 < len(a) else None
    try: rep = generate(name, closest, "--force" in a, "--dry-run" in a)
    except Refused as e:
        print(str(e.code) if not isinstance(e.code, int) else e, file=sys.stderr); sys.exit(1)
    if "--json" in a: print(json.dumps(rep, indent=1, ensure_ascii=False)); return
    print(f"method {rep['method']} ({rep['dir']})" + (" - dry run, nothing written" if rep["dry_run"] else ""))
    for k in ("written", "unchanged", "removed", "kept"):
        if rep[k]: print(f"  {k}: " + ", ".join(rep[k]))
    for n in rep["notes"]: print("  NOTE:", n)
    if rep["kept"]: print("  KEPT files were not overwritten - check them, or run again with --force to replace them with the card's version")
    print(f"next: dbcx smoke {rep['method']} (the example run) and dbcx method check {rep['method']}")


if __name__ == "__main__":
    main()
