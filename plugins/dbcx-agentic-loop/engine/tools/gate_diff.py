#!/usr/bin/env python3
"""Changed cells between the customer workbooks of two gate rounds - the blind re-read's only account of what changed (G9).

Usage: dbcx gate diff <round> [--against <k>]      (also: dbcx gate_diff <round> ...)
Compares analysis/gate/round<k>-workbooks/ (default k = round - 1) with analysis/gate/round<round>-workbooks/ (the snapshot the round's
briefs took; the current deliverables/ when it is missing yet). Table sheets are compared row by row on the row's first cell (ID) and
the column header, every other sheet cell by cell; a formula counts as changed when its text or its cached value changed.
Writes analysis/gate/round<round>-diff.md and prints its path and the change count. Tool output, never orchestrator prose.
"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import RUN as ROOT, relp

CAP = 60   # listed changes per sheet; the rest is counted

def snapshot_dir(rnd): return os.path.join(ROOT, "analysis", "gate", f"round{rnd}-workbooks")

def cells(path):
    """{sheet: {"table": bool, "cells": {key: shown value}}} - key = (row id, header) on table sheets, the coordinate elsewhere"""
    import openpyxl
    from lint_deliverable import header_row, qualified
    wb = openpyxl.load_workbook(path); vb = openpyxl.load_workbook(path, data_only=True); out = {}
    for ws in wb:
        hr = header_row(ws)   # 2 below option band headers
        hdr = qualified(ws, hr, [c.value for c in ws[hr]]) if ws.max_row else []   # band sheets: "Migration: Vorgehen"
        firsts = [ws.cell(r, 1).value for r in range(hr + 1, ws.max_row + 1)]
        table = (bool(ws.tables) or ws.freeze_panes is not None) and sum(isinstance(h, str) for h in hdr) >= 2 and len([x for x in firsts if x not in (None, "")]) == len({x for x in firsts if x not in (None, "")})
        got = {}
        for row in ws.iter_rows():
            for c in row:
                if c.value is None: continue
                v = c.value; cached = vb[ws.title][c.coordinate].value
                shown = f"{v} [= {cached}]" if isinstance(v, str) and v.startswith("=") and cached is not None else str(v)
                if table and c.row > hr:
                    rid = ws.cell(c.row, 1).value
                    if rid in (None, ""): continue
                    got[(str(rid), str(hdr[c.column - 1]) if c.column - 1 < len(hdr) and hdr[c.column - 1] is not None else c.column_letter)] = shown
                else: got[c.coordinate] = shown
        out[ws.title] = {"table": table, "cells": got}
    return out

def fmt_key(k): return f"{k[0]} · {k[1]}" if isinstance(k, tuple) else k

def diff_books(old, new):
    lines = []; total = 0
    for s in [x for x in new if x not in old]: lines.append(f"- sheet **{s}** added"); total += 1
    for s in [x for x in old if x not in new]: lines.append(f"- sheet **{s}** removed"); total += 1
    for s in [x for x in new if x in old]:
        a, b = old[s]["cells"], new[s]["cells"]; ch = []
        for k in sorted(set(a) | set(b), key=lambda k: str(k)):
            if a.get(k) != b.get(k): ch.append(f"  - {fmt_key(k)}: {str(a.get(k, '(empty)'))[:160]} → {str(b.get(k, '(empty)'))[:160]}")
        if ch:
            total += len(ch); lines.append(f"- sheet **{s}**: {len(ch)} changed cell(s)"); lines += ch[:CAP]
            if len(ch) > CAP: lines.append(f"  - … {len(ch) - CAP} more")
    return total, lines

def diff(rnd, against=None):
    k = against if against is not None else rnd - 1
    old_dir = snapshot_dir(k); new_dir = snapshot_dir(rnd) if os.path.isdir(snapshot_dir(rnd)) else os.path.join(ROOT, "deliverables")
    if not os.path.isdir(old_dir): sys.exit(f"no snapshot of round {k} ({relp(old_dir, ROOT)}) - the round's gate briefs take it; nothing to compare")
    names = sorted({os.path.basename(f) for f in glob.glob(os.path.join(old_dir, "*.xlsx")) + glob.glob(os.path.join(new_dir, "*.xlsx"))})
    out = [f"# Changes in the customer workbooks: round {k} → round {rnd}", "", f"Generated by `dbcx gate diff {rnd}` from `{relp(old_dir, ROOT)}` and `{relp(new_dir, ROOT)}`. Table rows are keyed by their first cell (ID) and the column header; `[= x]` is the value Excel calculated.", ""]
    total = 0
    for n in names:
        o, w = os.path.join(old_dir, n), os.path.join(new_dir, n)
        if not os.path.exists(o): out += [f"## {n}", "- workbook added", ""]; total += 1; continue
        if not os.path.exists(w): out += [f"## {n}", "- workbook removed", ""]; total += 1; continue
        t, lines = diff_books(cells(o), cells(w)); total += t
        out += [f"## {n} ({t} change(s))"] + (lines or ["- unchanged"]) + [""]
    p = os.path.join(ROOT, "analysis", "gate", f"round{rnd}-diff.md"); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote {relp(p, ROOT)} ({total} change(s) across {len(names)} workbook(s))")
    return p

def main():
    a = sys.argv[1:]
    if not a or not a[0].isdigit(): print(__doc__); sys.exit(1)
    diff(int(a[0]), int(a[a.index("--against") + 1]) if "--against" in a else None)

if __name__ == "__main__":
    main()
